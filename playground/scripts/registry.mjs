#!/usr/bin/env node
// Scans app/prototypes/*/metadata.json and writes lib/prototype-registry.generated.ts.
// Runs automatically before dev, build, lint and typecheck. Pass --watch to keep it in sync during `npm run dev`.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const prototypesDir = path.join(root, "app/prototypes");
const outFile = path.join(root, "lib/prototype-registry.generated.ts");
const REQUIRED = ["title", "description", "tags", "folder", "createdAt", "updatedAt", "hidden", "public"];
// Keep in sync with lib/folders.ts (minus "docs", which holds documents, not prototypes).
const FOLDERS = ["design-system", "pine-one", "pine-one-app", "pine-omni", "pine-omni-app", "agents", "onboarding"];

function exists(rel) {
  return fs.existsSync(path.join(root, "public", rel));
}

function readPrototypes() {
  const errors = [];
  const entries = [];
  for (const dirent of fs.readdirSync(prototypesDir, { withFileTypes: true })) {
    if (!dirent.isDirectory() || /^[[_(]/.test(dirent.name)) continue;
    const slug = dirent.name;
    const dir = path.join(prototypesDir, slug);
    const metaPath = path.join(dir, "metadata.json");
    if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(slug)) errors.push(`${slug}: folder name must be kebab-case`);
    if (!fs.existsSync(metaPath)) {
      errors.push(`${slug}: missing metadata.json`);
      continue;
    }
    if (!fs.existsSync(path.join(dir, "page.tsx"))) errors.push(`${slug}: missing page.tsx`);
    if (!fs.existsSync(path.join(dir, "HOW_IT_WORKS.md"))) errors.push(`${slug}: missing HOW_IT_WORKS.md`);
    let meta;
    try {
      meta = JSON.parse(fs.readFileSync(metaPath, "utf8"));
    } catch (e) {
      errors.push(`${slug}: metadata.json is not valid JSON (${e.message})`);
      continue;
    }
    for (const key of REQUIRED) if (!(key in meta)) errors.push(`${slug}: metadata.json is missing "${key}"`);
    if (meta.updatedAt && Number.isNaN(Date.parse(meta.updatedAt))) errors.push(`${slug}: updatedAt is not a valid date`);
    if (!Array.isArray(meta.tags)) errors.push(`${slug}: tags must be an array`);
    if (meta.external && !["phone", "none"].includes(meta.external.embed))
      errors.push(`${slug}: external.embed must be "phone" or "none"`);
    if ("folder" in meta && !FOLDERS.includes(meta.folder))
      errors.push(`${slug}: folder must be one of ${FOLDERS.join(", ")}`);
    if ("surface" in meta && !["web", "mobile"].includes(meta.surface))
      errors.push(`${slug}: surface must be "web" or "mobile"`);
    if ("group" in meta && (typeof meta.group !== "string" || !meta.group.trim()))
      errors.push(`${slug}: group must be a non-empty string`);
    const seed = meta.external?.seedLocalStorage;
    if (seed && (typeof seed !== "object" || Object.values(seed).some((v) => typeof v !== "string")))
      errors.push(`${slug}: external.seedLocalStorage must map keys to strings`);
    entries.push({
      slug,
      thumbnails: exists(`thumbnails/${slug}-light.png`),
      ogImage: exists(`og/${slug}.png`),
      ogVideo: exists(`og/${slug}.mp4`) ? "mp4" : exists(`og/${slug}.webm`) ? "webm" : null,
      variantOf: meta.variantOf,
    });
  }
  const slugs = new Set(entries.map((e) => e.slug));
  for (const e of entries) {
    const target = e.variantOf;
    if (target === undefined) continue;
    if (typeof target !== "string" || !slugs.has(target)) errors.push(`${e.slug}: variantOf "${target}" is not an existing prototype`);
    else if (target === e.slug) errors.push(`${e.slug}: variantOf can't point at itself`);
  }
  return { errors, entries: entries.sort((a, b) => a.slug.localeCompare(b.slug)) };
}

function write() {
  const { errors, entries } = readPrototypes();
  if (errors.length) {
    console.error(`\n[registry] Fix these before continuing:\n  - ${errors.join("\n  - ")}\n`);
    return false;
  }
  const lines = [
    "// AUTO-GENERATED by scripts/registry.mjs. Do not edit; it is rewritten on dev/build.",
    'import type { PrototypeMeta, RegistryEntry } from "./prototypes";',
    ...entries.map((e, i) => `import meta${i} from "@/app/prototypes/${e.slug}/metadata.json";`),
    "",
    "export const registry: RegistryEntry[] = [",
    ...entries.map(
      (e, i) =>
        `  { slug: ${JSON.stringify(e.slug)}, meta: meta${i} as PrototypeMeta, assets: { thumbnails: ${e.thumbnails}, ogImage: ${e.ogImage}, ogVideo: ${JSON.stringify(e.ogVideo)} }, load: () => import("@/app/prototypes/${e.slug}/page") },`
    ),
    "];",
    "",
  ];
  const next = lines.join("\n");
  const prev = fs.existsSync(outFile) ? fs.readFileSync(outFile, "utf8") : "";
  if (next !== prev) {
    fs.writeFileSync(outFile, next);
    console.log(`[registry] ${entries.length} prototypes`);
  }
  return true;
}

const ok = write();
if (process.argv.includes("--watch")) {
  let timer;
  const rerun = () => {
    clearTimeout(timer);
    timer = setTimeout(write, 150);
  };
  fs.watch(prototypesDir, { recursive: true }, (_e, file) => {
    if (!file || file.endsWith("metadata.json") || !file.includes(path.sep)) rerun();
  });
  fs.watch(path.join(root, "public"), { recursive: true }, rerun);
  console.log("[registry] watching app/prototypes");
} else if (!ok) {
  process.exit(1);
}
